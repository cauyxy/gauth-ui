type Shape = [tag: string, attrs: Record<string, string>]

/** The shapes of one Lucide icon, read from its file. */
function shapesOf(lucideName: string): Shape[] {
  const source = readFileSync(`${LUCIDE}dist/esm/icons/${lucideName}.mjs`, 'utf8')
  /* A name Lucide has replaced points to its new file. */
  const renamed = source.match(/export \{ default \} from '\.\/([\w-]+)\.mjs'/)?.[1]
  if (renamed) return shapesOf(renamed)
  /* The list after `node:`, up to the bracket that closes it. */
  const start = source.indexOf('node: [') + 'node: '.length
  let end = start
  for (let depth = 0; end < source.length; end++) {
    if (source[end] === '[') depth++
    if (source[end] === ']' && --depth === 0) break
  }
  if (start < 'node: '.length || end === source.length) throw new Error(`Cannot read the drawing of ${lucideName}`)
  const node = source.slice(start, end + 1)
  const shapes = new Function(`return ${node}`)() as [string, Record<string, string>][]
  return shapes.map(([tag, { key: _key, ...attrs }]) => [tag, attrs])
}

export function iconsFile() {
  const version = JSON.parse(readFileSync(`${LUCIDE}package.json`, 'utf8')).version as string
  const rows = Object.entries(NAMES).map(([name, lucideName]) => `  ${JSON.stringify(name)}: ${JSON.stringify(shapesOf(lucideName))},`)
  return [
    `/* Generated by scripts/icons.ts from lucide-react ${version}. Never edit by hand. Drawings: Lucide Icons and Contributors, ISC license (THIRD-PARTY-NOTICES.md). */`,
    '/** Each icon as its shapes on a 24 by 24 grid. */',
    'export const ICONS = {',
    ...rows,
    '} as const satisfies Record<string, readonly (readonly [string, Record<string, string>])[]>',
    '',
  ].join('\n')
}

const FILE = `${ROOT}src/core/icons.ts`
export const staleIcons = () => {
  try {
    return readFileSync(FILE, 'utf8') === iconsFile() ? [] : ['src/core/icons.ts']
  } catch {
    return ['src/core/icons.ts']
  }
}

if (import.meta.main) {
  if (process.argv.includes('--check')) {
    if (staleIcons().length) {
      console.error('src/core/icons.ts is out of date. Run `pnpm icons`.')
      process.exit(1)
    }
  } else writeFileSync(FILE, iconsFile())
}
